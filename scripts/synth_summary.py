#!/usr/bin/env python3
"""
Team TLE - Phase II synthesis summary.

Run `make synth` first. Reads the Yosys / nextpnr outputs in synth/ and writes
synth/synthesis_summary.md (the table used in the paper).

It also fails if any output port of a synthesized netlist is tied to a
constant: that means the synthesizer optimised the design away (for example
an instruction ROM that lost its $readmemh image), and the numbers would be
meaningless.
"""

import json
import os
import re
import sys

TOPS = [("harvard_cpu_top", "Harvard"), ("von_neumann_top", "Von Neumann")]
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SYN = os.path.join(ROOT, "synth")


def constant_ports(top):
    with open(os.path.join(SYN, f"{top}_ecp5.json")) as f:
        mod = json.load(f)["modules"][top]
    return [p for p, v in mod["ports"].items() if any(isinstance(b, str) for b in v["bits"])]


def ecp5(top):
    with open(os.path.join(SYN, f"{top}_ecp5_pnr.json")) as f:
        rpt = json.load(f)
    util = rpt["utilization"]
    return {
        "comb": util["TRELLIS_COMB"]["used"],
        "ff": util["TRELLIS_FF"]["used"],
        "bram": util["DP16KD"]["used"],
        "comb_avail": util["TRELLIS_COMB"]["available"],
        "bram_avail": util["DP16KD"]["available"],
        "fmax": rpt["fmax"]["clk"]["achieved"],
    }


def artix7(top):
    with open(os.path.join(SYN, f"{top}_artix7.rpt")) as f:
        text = f.read()
    cells = {name: int(n) for n, name in re.findall(r"^\s+(\d+)\s+([A-Z][A-Z0-9_]+)$", text, re.M)}
    luts = sum(n for name, n in cells.items() if re.fullmatch(r"LUT[1-6]|INV", name))
    ffs = sum(n for name, n in cells.items() if re.fullmatch(r"FD[A-Z]{2}", name))
    bram = cells.get("RAMB18E1", 0) * 0.5 + cells.get("RAMB36E1", 0)
    return {"lut": luts, "ff": ffs, "bram36": bram, "carry4": cells.get("CARRY4", 0)}


def main():
    needed = [os.path.join(SYN, f"{top}_ecp5.json") for top, _ in TOPS]
    if not all(os.path.exists(p) for p in needed):
        sys.exit("synth/*_ecp5.json not found - run `make synth` first "
                 "(it runs this script at the end)")
    bad = {top: constant_ports(top) for top, _ in TOPS}
    if any(bad.values()):
        for top, ports in bad.items():
            if ports:
                print(f"ERROR: {top}: output ports tied to constants: {ports}", file=sys.stderr)
        sys.exit(1)

    rows = []
    for top, label in TOPS:
        e, a = ecp5(top), artix7(top)
        rows.append((label, top, e, a))

    lines = [
        "# Synthesis summary (generated by scripts/synth_summary.py)",
        "",
        "Lattice ECP5 LFE5U-25F: Yosys `synth_ecp5` + nextpnr-ecp5 place and route "
        "(out-of-context, 100 MHz target, seed 1). Fmax is the post-route value.",
        "Xilinx Artix-7: Yosys `synth_xilinx -family xc7` resource estimate only "
        "(no Vivado place and route, so no Artix-7 Fmax).",
        "",
        "| System | ECP5 logic cells (TRELLIS_COMB) | ECP5 FF | ECP5 DP16KD BRAM | ECP5 Fmax (MHz) "
        "| Artix-7 LUT | Artix-7 FF | Artix-7 BRAM (RAMB36 eq.) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for label, top, e, a in rows:
        lines.append(
            f"| {label} (`{top}`) | {e['comb']} / {e['comb_avail']} | {e['ff']} | "
            f"{e['bram']} / {e['bram_avail']} | {e['fmax']:.2f} | {a['lut']} | {a['ff']} | {a['bram36']:g} |"
        )
    lines.append("")
    lines.append("All netlist output ports are driven by logic (constant-port check passed).")
    out = os.path.join(SYN, "synthesis_summary.md")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
